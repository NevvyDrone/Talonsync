"""The Talon Program Library (TalonSync 1.10.2+): ready-made Talon Enhanced BASIC programs and games for the PDA's Terminal.

Pick one by number; nobody needs to know BASIC to play. Every program is plain BASIC, so it can also be opened in BASIC
to read (LIST) and change. They are also written into the Programs folder, so LOAD "GUESS" works too.
The screen is 30 x 8: every PRINT here fits in 30 columns.
"""
from __future__ import annotations

from typing import Dict, List

# (file name, title, kind, description, program)
PROGRAMS: List[Dict[str, str]] = []


def _add(name, title, kind, about, src):
    PROGRAMS.append(dict(name=name, title=title, kind=kind, about=about,
                         source="\n".join(l.strip() for l in src.strip().splitlines())))


